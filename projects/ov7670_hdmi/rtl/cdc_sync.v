// ============================================================================
// 2FF 同期化 (1bit レベル / トグル信号用)
//   多ビットの値は「値を保持したままトグルを送る」方式で、受け側はトグル変化を
//   検出してから値を取り込む (値は次のトグルまで変化しないことを送り側が保証する)
// ============================================================================
module cdc_sync #(
    parameter W = 1
)(
    input  wire         clk,
    input  wire [W-1:0] d,
    output wire [W-1:0] q
);
    reg [W-1:0] s1, s2;
    initial begin s1 = 0; s2 = 0; end
    always @(posedge clk) begin
        s1 <= d;
        s2 <= s1;
    end
    assign q = s2;
endmodule
